Pushing your changes into the Repository: (In Terminal [Ctrl+ü])

---1. Stage your changes:
        git add .
    (This stages all changes in the current directory)

---2. Check status:
        git status
    (Displays the current state of your working directory and staging area)

---3. Commit your changes:
        git commit -m "your commit message"
    (Commits the staged changes with a message describing the update)

---4. Push to the repository:
        git push
            or
        git push origin main
    (Pushes your changes to the remote repository on the specified branch)

---5. Check that push was successful:
        git status
    (Ensures your working directory is clean and no pending changes exist)

